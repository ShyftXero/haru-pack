# INV-SECRET-01 — the typed secret is never echoed
# --------------------------------------------------------------------------------------

def _prompt_over_pty(harness_exe: Path, blob: bytes, tmp_path: Path, typed: bytes,
                     timeout: float = 30.0) -> tuple[bytes, int]:
    """Run the decryptor on a real pty with ECHO left ON, type `typed`, return (output, rc).

    ECHO on is the point: that is what a terminal does, and it is why `stdin.readLine()`
    leaks. A no-echo read turns ECHO off for the duration, so the typed bytes never come
    back down the master. Nothing here simulates the terminal — it is a kernel pty.
    """
    box, out = tmp_path / "box.bin", tmp_path / "out.bin"
    out.unlink(missing_ok=True)
    box.write_bytes(blob)
    env = dict(os.environ)
    env.pop("HARUPACK_SECRET", None)
    master, slave = pty.openpty()
    proc = subprocess.Popen([str(harness_exe), str(box), str(out)],
                            stdin=slave, stdout=slave, stderr=slave, env=env, close_fds=True)
    os.close(slave)
    captured = bytearray()
    sent = False
    deadline = time.time() + timeout
    try:
        while time.time() < deadline:
            r, _, _ = select.select([master], [], [], 0.2)
            if r:
                try:
                    chunk = os.read(master, 4096)
                except OSError:
                    break
                if not chunk:
                    break
                captured += chunk
            if not sent and b"License secret" in captured:
                time.sleep(0.3)        # let the reader finish turning ECHO off
                os.write(master, typed + b"\n")
                sent = True
            if sent and proc.poll() is not None:
                # drain whatever is still buffered in the pty
                while select.select([master], [], [], 0.2)[0]:
                    try:
                        chunk = os.read(master, 4096)
                    except OSError:
                        break
                    if not chunk:
                        break
                    captured += chunk
                break
        assert sent, f"never saw the secret prompt; got {bytes(captured)!r}"
        proc.wait(timeout=10)
    finally:
        if proc.poll() is None:
            proc.kill()
            proc.wait(timeout=10)
        os.close(master)
    return bytes(captured), proc.returncode


@pytest.mark.skipif(sys.platform == "win32", reason="pty is POSIX-only")
@pytest.mark.invariant("INV-SECRET-01")
def test_typed_secret_is_not_echoed_to_the_terminal(harness, container, tmp_path):
    """The load-bearing test for INV-SECRET-01, over a kernel pty with echo enabled.

    It also asserts the open SUCCEEDS: a no-echo read that mangles the secret would pass a
    'the secret is not on screen' assertion for entirely the wrong reason.
    """
    captured, rc = _prompt_over_pty(harness, container, tmp_path, SECRET)
    assert rc == 0, f"the secret typed at the prompt did not open the container: {captured!r}"
    assert (tmp_path / "out.bin").read_bytes() == PAYLOAD
    assert SECRET not in captured, (
        f"the license secret was echoed to the terminal: {captured!r} — it is now in the "
        f"scrollback, in `script` output, and in any CI log that captured this session"
    )
    assert b"License secret" in captured, "the prompt itself must still be shown"


@pytest.mark.skipif(sys.platform == "win32", reason="pty is POSIX-only")
@pytest.mark.invariant("INV-SECRET-01")
def test_the_echo_check_can_see_an_echo(harness, container, tmp_path):
    """Guard-of-guards. If the pty were misconfigured (ECHO off at the master, or the
    input never reaching the child), the test above would pass no matter what the reader
    does. So: type a wrong secret at the same prompt through the same path and require
    that the harness saw it — proof the bytes really are delivered and the open really is
    driven by what was typed."""
    captured, rc = _prompt_over_pty(harness, container, tmp_path, b"definitely-wrong-secret")
    assert rc == 5, f"a wrong typed secret must fail the open; rc={rc} out={captured!r}"
    assert b"tampered payload" in captured or b"wrong secret" in captured, captured
    assert b"definitely-wrong-secret" not in captured, (
        "even a wrong secret must not be echoed — users mistype their real one"
    )


