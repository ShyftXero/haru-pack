"""INV-CRYPTO-04 / INV-CRYPTO-05 / INV-CRYPTO-06 / INV-SECRET-01 — the hardened container.

These tests are stronger than the rest of the crypto suite in one specific way: most of
them compile `cryptbox.nim` and run it. The container is written by Python and opened by
the real Nim decryptor, in a subprocess, on containers this file mutates byte by byte.
`tests/test_container.py` can only read the Nim as data; here the Nim is the thing under
test, so an offset that agrees on paper but disagrees in practice cannot pass.

What is proven here, precisely:
  * a v2 container written by `crypto.encrypt` is opened by `cryptbox.openContainer`
    (real AES-GCM interop, not a parity assertion about offsets);
  * flipping a header byte that plays NO part in key derivation is rejected — so the
    rejection is attributable to the AEAD tag, which is exactly what INV-CRYPTO-04 claims
    and what the old fixed-magic AAD could not do;
  * a secret typed at the prompt is not echoed, checked over a real pty with ECHO on;
  * a forged (but correctly authenticated) plaintext with a nonsense policy length is
    refused with a diagnostic, not a crash.

What is NOT proven here: constant-time behavior of the tag comparison. That is asserted
against the source, and it is labelled as such — a timing measurement in a pytest
subprocess would be noise, and a green noise-test is worse than an honest source check.
"""
from __future__ import annotations

import os
import pty
import re
import select
import shutil
import struct
import subprocess
import sys
import time
from pathlib import Path

import pytest
from cryptography.exceptions import InvalidTag
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

from haru_pack import crypto

REPO = Path(__file__).resolve().parent.parent
LAUNCHER_DIR = REPO / "src/haru_pack/launcher"
NIM_CRYPTBOX = LAUNCHER_DIR / "cryptbox.nim"
NIM = shutil.which("nim")

SECRET = b"s3cret-license-key"
PAYLOAD = b"PK\x03\x04not-really-a-zip-but-it-round-trips"
ITERS = 2_000                      # keep PBKDF2 out of the way; iters is authenticated, not secret

# A harness that is only the code path the launcher itself takes: isEncrypted -> openContainer.
HARNESS_NIM = """\
## Generated by tests/test_crypto_hardening.py. Exercises cryptbox.nim as the launcher does.
import std/os
import cryptbox

when isMainModule:
  let raw = readFile(paramStr(1))
  if not isEncrypted(raw): quit("harness: not an encrypted container", 9)
  let payload = openContainer(raw)
  writeFile(paramStr(2), payload)
  echo "HARNESS-OK ", payload.len
"""


@pytest.fixture(scope="module")
def harness(tmp_path_factory) -> Path:
    """Compile cryptbox.nim into a runnable decryptor.

    A compile failure is a hard failure, not a skip: a cryptbox.nim that does not build is
    a bricked launcher for every encrypted build.
    """
    if NIM is None:
        pytest.skip("nim not installed; the cross-implementation tests need the real decryptor")
    d = tmp_path_factory.mktemp("cryptbox-harness")
    src = d / "harness.nim"
    src.write_text(HARNESS_NIM, encoding="utf-8")
    exe = d / "harness"
    r = subprocess.run(
        [NIM, "c", "-d:release", f"--path:{LAUNCHER_DIR}", f"--nimcache:{d / 'nimcache'}",
         f"--out:{exe}", str(src)],
        capture_output=True, text=True, cwd=REPO,
    )
    assert r.returncode == 0 and exe.exists(), (
        "cryptbox.nim does not compile — every encrypted build is bricked:\n"
        f"{r.stdout[-4000:]}\n{r.stderr[-4000:]}"
    )
    return exe


def _run(harness_exe: Path, blob: bytes, tmp_path: Path, *,
         secret: bytes | None = SECRET, env_extra: dict[str, str] | None = None):
    """Open `blob` with the real Nim decryptor. Returns (CompletedProcess, payload|None)."""
    box = tmp_path / "box.bin"
    out = tmp_path / "out.bin"
    out.unlink(missing_ok=True)     # a stale file from an earlier run in the same tmp_path
    box.write_bytes(blob)           # would read as "this container opened"
    env = dict(os.environ)
    env.pop("HARUPACK_SECRET", None)
    if secret is not None:
        env["HARUPACK_SECRET"] = secret.decode()
    env.update(env_extra or {})
    proc = subprocess.run([str(harness_exe), str(box), str(out)],
                          capture_output=True, text=True, env=env, timeout=60,
                          stdin=subprocess.DEVNULL)   # never inherit a tty: it would prompt
    return proc, (out.read_bytes() if out.exists() else None)


def _forge(plaintext: bytes, secret: bytes = SECRET) -> bytes:
    """Assemble a v2 container around arbitrary plaintext, correctly authenticated.

    Deliberately does not call `crypto.encrypt`: it lets these tests produce plaintexts
    the encryptor would never emit (a lying policy length), which is the only way to reach
    the post-decryption bounds checks with a container that genuinely passes the tag check.
    """
    salt, nonce = os.urandom(16), os.urandom(12)
    key = crypto.derive_key(secret, salt, ITERS, None, None)
    head_a = (crypto.MAGIC + struct.pack("<HHI", crypto.CONTAINER_VERSION, 0, ITERS)
              + salt + nonce)
    head_b = struct.pack("<H", 0)
    ct_tag = AESGCM(key).encrypt(nonce, plaintext, head_a + head_b)
    return head_a + ct_tag[-16:] + head_b + ct_tag[:-16]


@pytest.fixture
def container() -> bytes:
    """Unbound container: no machine/user binding, so `flags` does NOT feed the KDF.

    That is the whole point. With a bound container a flags edit changes the derived key
    and the open fails for the old, weaker reason. Unbound, the key is identical before
    and after the edit, so a rejection can only have come from the AEAD tag.
    """
    return crypto.encrypt(PAYLOAD, SECRET, iters=ITERS)


def _aad_or_rejected(blob: bytes) -> bytes | None:
    """The AAD for `blob`, or None if the header no longer parses (also a detection)."""
    try:
        return crypto.container_aad(blob)
    except ValueError:
        return None


def _nim_consts() -> dict[str, int]:
    src = NIM_CRYPTBOX.read_text(encoding="utf-8")
    out = {}
    for name, pat in [("ContainerVersion", r"ContainerVersion\s*=\s*(\d+)'u16"),
                      ("TagOff", r"TagOff\s*=\s*(\d+)"),
                      ("HdrFixed", r"HdrFixed\s*=\s*(\d+)")]:
        m = re.search(pat, src)
        assert m, f"cryptbox.nim no longer declares {name}"
        out[name] = int(m.group(1))
    return out


def _nim_proc(name: str) -> str:
    src = NIM_CRYPTBOX.read_text(encoding="utf-8")
    start = src.index(f"proc {name}")
    rest = src[start + 1:]
    nxt = re.search(r"^proc ", rest, re.M)
    return rest[:nxt.start()] if nxt else rest


