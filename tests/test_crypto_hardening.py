@pytest.mark.invariant("INV-CRYPTO-05")
def test_tag_comparison_has_no_early_exit():
    """The old loop was `if tag[i] != box.tag[i]: quit(...)` — it returns after the first
    differing byte, which leaks the length of the matching prefix by timing.

    This reads the source, and that is a real limitation: it proves the shape of the
    comparison, not its timing. A timing assertion inside pytest would measure the
    scheduler.
    """
    body = _nim_proc("openContainer")
    loop = re.search(r"for i in 0 \.\.< 16:.*", body)
    assert loop, "no 16-byte tag comparison loop found in openContainer"
    assert "quit" not in loop.group(0), (
        "the tag comparison exits the loop early — restore the accumulate-then-compare form"
    )
    assert re.search(r"diff\s*=\s*diff\s+or\s*\(\s*tag\[i\]\s+xor\s+box\.tag\[i\]\s*\)",
                     loop.group(0)), loop.group(0)
    assert re.search(r"if\s+diff\s*!=\s*0'u8:\s*\n\s*quit", body), (
        "the accumulated difference is never acted on — a container with any tag would open"
    )


@pytest.mark.invariant("INV-CRYPTO-05")
def test_a_wrong_tag_is_still_rejected(harness, container, tmp_path):
    """Constant-time is worthless if it stopped rejecting. Flip each end of the tag."""
    for offset in (44, 59):
        mutated = bytearray(container)
        mutated[offset] ^= 0x80
        proc, payload = _run(harness, bytes(mutated), tmp_path)
        assert proc.returncode != 0 and payload is None, (
            f"a container with a corrupted tag byte at {offset} was accepted"
        )
        assert "tampered payload" in proc.stderr, proc.stderr


