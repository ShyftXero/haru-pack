@pytest.mark.invariant("INV-CRYPTO-02")
@pytest.mark.invariant("INV-CRYPTO-04")
def test_nim_opens_a_python_written_v2_container(harness, container, tmp_path):
    """The evidence gap this repo was carrying: nothing ever ran both implementations.

    If the Python AAD and the Nim AAD differ by one byte, this fails — and it is the only
    test in the suite that would notice, since offset-parity checks read the Nim as text.
    """
    proc, payload = _run(harness, container, tmp_path)
    assert proc.returncode == 0, f"the real decryptor rejected a fresh container: {proc.stderr}"
    assert payload == PAYLOAD


@pytest.mark.invariant("INV-CRYPTO-04")
def test_flags_edit_is_detected_by_the_tag_not_by_a_key_mismatch(container):
    """The exact red-path INVARIANTS.md writes for INV-CRYPTO-04.

    The container is unbound, so the derived key is provably unchanged by the edit (that
    is asserted, not assumed). The only thing left that can reject it is the tag.
    """
    mutated = bytearray(container)
    mutated[10] ^= crypto.BIND_MACHINE          # the flags field lives at offset 10
    mutated = bytes(mutated)

    salt = container[16:32]
    iters = struct.unpack_from("<I", container, 12)[0]
    key_before = crypto.derive_key(SECRET, salt, iters, None, None)
    key_after = crypto.derive_key(SECRET, mutated[16:32],
                                  struct.unpack_from("<I", mutated, 12)[0], None, None)
    assert key_before == key_after, (
        "precondition: this test only proves tag-attribution if the edit leaves the key alone"
    )
    assert struct.unpack_from("<H", mutated, 10)[0] != struct.unpack_from("<H", container, 10)[0]

    nonce = mutated[32:44]
    tag = mutated[44:60]
    eslen = struct.unpack_from("<H", mutated, 60)[0]
    ct = mutated[62 + eslen:]
    with pytest.raises(InvalidTag):
        AESGCM(key_before).decrypt(nonce, ct + tag, crypto.container_aad(mutated))

    # ...and the pre-INV-CRYPTO-04 reader (AAD = bare magic) would have accepted it happily,
    # which is what made the old behavior "fail-closed" rather than "tamper-evident".
    with pytest.raises(InvalidTag):
        AESGCM(key_before).decrypt(nonce, ct + tag, crypto.MAGIC)


@pytest.mark.invariant("INV-CRYPTO-04")
def test_nim_rejects_a_flags_edit_with_the_correct_secret(harness, container, tmp_path):
    """Same edit, run through the real decryptor with the right secret in the environment.

    Control first: the unmutated container opens. So the rejection below is the edit.
    """
    ok, payload = _run(harness, container, tmp_path)
    assert ok.returncode == 0 and payload == PAYLOAD, "control: the clean container must open"

    mutated = bytearray(container)
    mutated[10] ^= crypto.BIND_MACHINE
    proc, payload = _run(harness, bytes(mutated), tmp_path)
    assert proc.returncode != 0, (
        "the Nim decryptor accepted a container whose flags byte was edited — the header "
        "is not in the AAD on the Nim side, so the two implementations disagree"
    )
    assert "tampered payload" in proc.stderr, proc.stderr
    assert payload is None


@pytest.mark.invariant("INV-CRYPTO-04")
@pytest.mark.parametrize("field,offset", [("version", 8), ("flags", 10), ("iters", 12),
                                          ("nonce", 32), ("esecret_len", 60)])
def test_every_header_field_is_inside_the_aad(container, field, offset):
    """Byte-level coverage map of the header. If a field falls out of the AAD, only its
    parametrization goes red, so the failure names the field that regressed."""
    mutated = bytearray(container)
    mutated[offset] ^= 0x01
    assert _aad_or_rejected(bytes(mutated)) != crypto.container_aad(container), (
        f"{field} at offset {offset} is not covered by the AAD"
    )


@pytest.mark.invariant("INV-CRYPTO-04")
def test_the_tag_field_is_the_only_header_bytes_outside_the_aad(container):
    """A GCM tag cannot authenticate itself; everything else before the ciphertext must be
    in. Stated as an equality so a future 'small' header addition cannot silently escape."""
    eslen = struct.unpack_from("<H", container, 60)[0]
    header = container[:62 + eslen]
    aad = crypto.container_aad(container)
    assert aad == header[:44] + header[60:]
    assert len(aad) == len(header) - 16
    for off in range(len(header)):
        if 44 <= off < 60:
            continue
        mutated = bytearray(container)
        mutated[off] ^= 0x01
        assert _aad_or_rejected(bytes(mutated)) != aad, (
            f"header byte {off} is outside the AAD"
        )


@pytest.mark.invariant("INV-CRYPTO-04")
def test_version_is_bumped_and_both_implementations_agree(container):
    """The format changed, so the version field must say so — otherwise a v1 container and
    a v2 container are indistinguishable and the failure reads as 'wrong secret'."""
    assert crypto.CONTAINER_VERSION == 2
    assert struct.unpack_from("<H", container, 8)[0] == 2
    consts = _nim_consts()
    assert consts["ContainerVersion"] == crypto.CONTAINER_VERSION
    assert consts["TagOff"] == crypto.TAG_OFF
    assert consts["HdrFixed"] == crypto.HDR_FIXED


@pytest.mark.invariant("INV-CRYPTO-02")
def test_nim_builds_the_same_aad_bytes(container):
    """Source-level parity for the AAD construction, in the style test_container.py uses
    for the offsets. Weaker than the interop test above; kept because it names the drift."""
    body = " ".join(_nim_proc("parseBox").split())
    assert "result.aad = b[0 ..< TagOff]" in body, body
    assert "result.aad.add b[TagOff+16 ..< HdrFixed+eslen]" in body, body


@pytest.mark.invariant("INV-CRYPTO-04")
def test_nim_refuses_a_version_1_container_before_asking_for_a_secret(harness, container,
                                                                     tmp_path):
    """A v1 container in front of a v2 launcher must say so, not fail as 'wrong secret'.
    Run with NO secret available: the version check has to fire first, or the user gets a
    prompt for a secret that could never have worked."""
    downgraded = bytearray(container)
    struct.pack_into("<H", downgraded, 8, 1)
    proc, _ = _run(harness, bytes(downgraded), tmp_path, secret=None)
    assert proc.returncode != 0
    assert "version" in proc.stderr, proc.stderr
    assert "License secret" not in proc.stderr, (
        "the launcher prompted for a secret before noticing the container is unreadable"
    )


