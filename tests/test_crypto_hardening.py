@pytest.mark.invariant("INV-CRYPTO-06")
def test_forged_plaintext_round_trips(harness, tmp_path):
    """Control for the two tests below: _forge produces containers the real reader accepts,
    so a rejection there is the bounds check and not a broken fixture."""
    policy = b'{"expires":"","geo":[],"machine":"","user":""}'
    blob = _forge(struct.pack("<I", len(policy)) + policy + PAYLOAD)
    proc, payload = _run(harness, blob, tmp_path)
    assert proc.returncode == 0, proc.stderr
    assert payload == PAYLOAD


@pytest.mark.invariant("INV-CRYPTO-06")
@pytest.mark.parametrize("plen", [0xFFFFFFFF, 0x7FFFFFFF, 4096])
def test_oversized_policy_length_is_refused_not_crashed(harness, tmp_path, plen):
    """An authenticated-but-nonsense policy length must produce a diagnostic exit.

    Reachable only by a secret-holder, so it is robustness rather than a bypass — but an
    out-of-range slice or a negative-length allocation in the launcher is a crash with no
    explanation, and on 32-bit it is a negative length passed to newString."""
    blob = _forge(struct.pack("<I", plen) + b'{"geo":[]}' + PAYLOAD)
    proc, payload = _run(harness, blob, tmp_path)
    assert proc.returncode == 5, f"rc={proc.returncode} err={proc.stderr}"
    assert "policy length" in proc.stderr, proc.stderr
    assert "Error: unhandled exception" not in proc.stderr and "Traceback" not in proc.stderr, (
        f"unhandled Nim defect instead of a bounds check: {proc.stderr}"
    )
    assert payload is None


@pytest.mark.invariant("INV-CRYPTO-06")
def test_plaintext_shorter_than_its_length_prefix_is_refused(harness, tmp_path):
    blob = _forge(b"\x01\x02")          # two bytes: not even a length prefix
    proc, _ = _run(harness, blob, tmp_path)
    assert proc.returncode == 5, f"rc={proc.returncode} err={proc.stderr}"
    assert "length prefix" in proc.stderr, proc.stderr


@pytest.mark.invariant("INV-CRYPTO-06")
def test_truncated_container_header_is_refused(harness, container, tmp_path):
    proc, _ = _run(harness, container[:40], tmp_path)
    assert proc.returncode == 5, f"rc={proc.returncode} err={proc.stderr}"
    assert "truncated" in proc.stderr, proc.stderr


